/* ==========================================================================
   Bascule FR / EN sans rechargement.
   - Le français reste dans le HTML (référencement, secours sans JavaScript).
   - L'anglais vient du dictionnaire I18N_DICT ci-dessus, par clés data-i18n.
   - Ordre de décision : choix mémorisé > paramètre ?lang= > langue du navigateur.
   Attributs reconnus :
     data-i18n="clé"                 contenu HTML de l'élément
     data-i18n-attr="attr:clé;..."   attributs (aria-label, content, alt, title)
     data-href-en / data-src-en      lien ou image propres à la version anglaise
     data-lang-only="fr|en"          élément affiché dans une seule langue
     data-i18n-num                   en anglais, nombres du bloc au format anglais
                                     (74,4 -> 74.4 ; 77 % -> 77%), textes inchangés
   ========================================================================== */
(function () {
    "use strict";

    var LANGS = ["fr", "en"];
    var KEY = "sln-lang";
    var root = document.documentElement;
    var listeners = [];
    var originals = new WeakMap();
    var textOriginals = new WeakMap();

    function toEnglishNumbers(str) {
        return str
            .replace(/(\d),(\d)/g, "$1.$2")
            .replace(/(\d)[\s\u00a0\u202f]%/g, "$1%")
            .replace(/(\d)\u202f(\d{3})/g, "$1,$2");
    }

    function readStored() {
        try { return window.localStorage.getItem(KEY); } catch (e) { return null; }
    }
    function writeStored(lang) {
        try { window.localStorage.setItem(KEY, lang); } catch (e) { /* stockage indisponible */ }
    }
    function fromQuery() {
        var m = /[?&]lang=([a-z]{2})\b/i.exec(window.location.search);
        return m ? m[1].toLowerCase() : null;
    }
    function fromBrowser() {
        var l = (navigator.languages && navigator.languages[0]) || navigator.language || "";
        return /^en\b/i.test(l) ? "en" : "fr";
    }
    function resolve() {
        var s = readStored();
        if (LANGS.indexOf(s) !== -1) return s;
        var q = fromQuery();
        if (LANGS.indexOf(q) !== -1) return q;
        return fromBrowser();
    }

    var current = resolve();
    root.lang = current;
    if (current !== "fr") {
        root.classList.add("i18n-wait");
        // filet de sécurité : la page ne reste jamais masquée
        setTimeout(function () { root.classList.remove("i18n-wait"); }, 1500);
    }

    function dict(lang) { return (window.I18N_DICT && window.I18N_DICT[lang]) || {}; }

    function t(key, lang) {
        lang = lang || current;
        var d = dict(lang);
        if (Object.prototype.hasOwnProperty.call(d, key)) return d[key];
        var f = dict("fr");
        if (Object.prototype.hasOwnProperty.call(f, key)) return f[key];
        return null;
    }

    function memo(el) {
        var o = originals.get(el);
        if (!o) { o = { attrs: {} }; originals.set(el, o); }
        return o;
    }

    function apply(lang) {
        var missing = [];

        document.querySelectorAll("[data-i18n]").forEach(function (el) {
            var o = memo(el);
            if (o.html === undefined) o.html = el.innerHTML;
            if (lang === "fr") { el.innerHTML = o.html; return; }
            var v = dict(lang)[el.getAttribute("data-i18n")];
            if (v === undefined) { missing.push(el.getAttribute("data-i18n")); return; }
            el.innerHTML = v;
        });

        document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
            var o = memo(el);
            el.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
                var p = pair.split(":");
                var attr = p[0].trim(), key = (p[1] || "").trim();
                if (!attr || !key) return;
                if (o.attrs[attr] === undefined) o.attrs[attr] = el.getAttribute(attr);
                if (lang === "fr") { el.setAttribute(attr, o.attrs[attr]); return; }
                var v = dict(lang)[key];
                if (v === undefined) { missing.push(key); return; }
                el.setAttribute(attr, v);
            });
        });

        ["href", "src"].forEach(function (attr) {
            document.querySelectorAll("[data-" + attr + "-en]").forEach(function (el) {
                var o = memo(el);
                if (o[attr] === undefined) o[attr] = el.getAttribute(attr);
                el.setAttribute(attr, lang === "en" ? el.getAttribute("data-" + attr + "-en") : o[attr]);
            });
        });

        document.querySelectorAll("[data-i18n-num]").forEach(function (box) {
            var walker = document.createTreeWalker(box, NodeFilter.SHOW_TEXT, null);
            var node;
            while ((node = walker.nextNode())) {
                if (lang === "en") {
                    if (!textOriginals.has(node)) textOriginals.set(node, node.nodeValue);
                    node.nodeValue = toEnglishNumbers(textOriginals.get(node));
                } else if (textOriginals.has(node)) {
                    node.nodeValue = textOriginals.get(node);
                }
            }
        });

        document.querySelectorAll("[data-lang-only]").forEach(function (el) {
            if (el.getAttribute("data-lang-only") === lang) el.removeAttribute("hidden");
            else el.setAttribute("hidden", "");
        });

        root.lang = lang;
        root.classList.remove("i18n-wait");
        if (missing.length && window.console) {
            console.warn("i18n : clés absentes pour " + lang + " : " + missing.join(", "));
        }
    }

    function set(lang, opts) {
        if (LANGS.indexOf(lang) === -1) return;
        if (!opts || opts.store !== false) writeStored(lang);
        if (lang === current && document.readyState !== "loading" && !(opts && opts.force)) return;
        current = lang;
        apply(lang);
        listeners.forEach(function (fn) { try { fn(lang); } catch (e) { console.error(e); } });
    }

    /* Nombres : virgule et espace fine en français, point en anglais */
    function num(x, digits) {
        if (x === null || x === undefined || isNaN(x)) return "";
        var d = digits === undefined ? 1 : digits;
        return Number(x).toLocaleString(current === "fr" ? "fr-FR" : "en-GB", {
            minimumFractionDigits: d, maximumFractionDigits: d
        });
    }
    function pct(x, digits) {
        return num(x, digits) + (current === "fr" ? " %" : "%");
    }

    window.SLN = {
        get lang() { return current; },
        set: set,
        t: t,
        num: num,
        pct: pct,
        onChange: function (fn) { listeners.push(fn); }
    };

    function init() {
        if (current !== "fr") apply(current);
        else root.classList.remove("i18n-wait");
        listeners.forEach(function (fn) { try { fn(current); } catch (e) { console.error(e); } });
    }
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
    else init();
})();
